import express from 'express';
import router from './routes/route.js';
import erroGlobal from './middlewares/erroGlobal.js';
import authRouter from './routes/auth.route.js';
import helmet from 'helmet'
import limiter from './middlewares/rate-limit.js';
import mongoSanitize from 'express-mongo-sanitize'
import isAdmin from './middlewares/isAdmin.js';
import adminRouter from './routes/admin.route.js';
import userRoute from './routes/user.route.js';
import cors from 'cors';
import cookieParser from 'cookie-parser';

const app = express();

app.use(cookieParser());

const allowedOrigins = [
  "https://projeto-loja-online.vercel.app",
  "http://localhost:5173",
  "http://127.0.0.1:5173",
];

// Preview URLs generated by Vercel for this project and team.
const vercelPreviewOrigin =
  /^https:\/\/projeto-loja-online-[a-z0-9-]+-guilherme-s-projects10\.vercel\.app$/;

app.use(cors({
  origin(origin, callback) {
    if (
      !origin ||
      allowedOrigins.includes(origin) ||
      vercelPreviewOrigin.test(origin)
    ) {
      return callback(null, true);
    }

    return callback(new Error("Origem não permitida pelo CORS"));
  },
  credentials: true,
  methods: ["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"],
  allowedHeaders: ["Content-Type", "Authorization"],
}));

app.use(helmet());
app.use(limiter);
// app.use(mongoSanitize({
//     replaceWith: '_'
// }));

app.use(express.json());

app.use(router);
app.use(authRouter);
app.use(adminRouter);
app.use(userRoute);

app.use(erroGlobal);

export default app;
